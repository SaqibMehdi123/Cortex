// One-off generator: extracts brand SVG paths from simple-icons into a
// self-contained React component so the landing page has zero runtime dep.
import { writeFileSync } from 'node:fs'
import * as icons from 'simple-icons'

const PICK = {
  siAnthropic: 'Anthropic',
  siGooglegemini: 'Google Gemini',
  siHuggingface: 'Hugging Face',
  siArxiv: 'arXiv',
  siGithub: 'GitHub',
  siMeta: 'Meta',
  siPytorch: 'PyTorch',
  siOllama: 'Ollama',
  siMistralai: 'Mistral AI',
  siX: 'X',
  siGooglescholar: 'Google Scholar',
  siDeepmind: 'DeepMind',
}

const entries = Object.entries(PICK).map(([key, title]) => {
  const icon = icons[key]
  if (!icon) throw new Error(`missing icon: ${key}`)
  return { title, hex: icon.hex, path: icon.path }
})

const body = `// AUTO-GENERATED by scripts/gen-brand-logos.mjs — do not edit by hand.
// Brand marks from simple-icons (CC0). Rendered monochrome via currentColor.

export interface BrandLogo {
  title: string
  hex: string
  path: string
}

export const BRAND_LOGOS: BrandLogo[] = ${JSON.stringify(entries, null, 2)}

export function BrandMark({
  logo,
  size = 18,
  className,
}: {
  logo: BrandLogo
  size?: number
  className?: string
}) {
  return (
    <svg
      role="img"
      aria-label={logo.title}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="currentColor"
      className={className}
    >
      <path d={logo.path} />
    </svg>
  )
}
`

writeFileSync('src/components/landing/brand-logos.tsx', body)
console.log('wrote', entries.length, 'logos')
